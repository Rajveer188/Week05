package com.tit.week05.day02.json.hands_on_problems.object_list_to_json_array;

public class Student {
    //attribute
    private String name;
    private int id;

    //constructor
    public Student(String name, int id) {
        this.name = name;
        this.id = id;
    }
    //getter
    public String getName() {
        return name;
    }
    public int getId() {
        return id;
    }
}
